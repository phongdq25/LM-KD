"""SPIN: Self-Play Fine-Tuning (Chen et al., ICML 2024).

SPIN pit the current model against previous-iteration self-play rollouts using
the DPO-style pairwise objective:
L_SPIN = -log sigmoid(beta * ((log pi(y) - log pi(y')) - (log pi_ref(y) - log pi_ref(y'))))

Source: APSP/trainers.py:89-109
"""

from __future__ import annotations

from typing import ClassVar

import torch
import torch.nn.functional as F

from baselines.self_play.common import _check_pairwise, _reduction_term, pairwise, sequence_logps
from lmkd.core.plugin import BaseConfig
from lmkd.core.registry import CRITERIONS
from lmkd.losses.base import Criterion, LossContext, LossOutput
from lmkd.models.forward import FeatureRequest, SideRequest
from lmkd.teachers.signals import TeacherSignalSpec


def spin_loss(
    policy_chosen_logps: torch.Tensor,
    policy_rejected_logps: torch.Tensor,
    reference_chosen_logps: torch.Tensor,
    reference_rejected_logps: torch.Tensor,
    *,
    beta: float = 0.1,
    label_smoothing: float = 0.0,
    reference_free: bool = False,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """SPIN pairwise preference objective against self-play generations.

    Args:
        policy_chosen_logps: Log probabilities of policy for ground truth / chosen y.
        policy_rejected_logps: Log probabilities of policy for self-play / rejected y'.
        reference_chosen_logps: Log probabilities of reference (iter t-1) for chosen y.
        reference_rejected_logps: Log probabilities of reference (iter t-1) for rejected y'.
        beta: Inverse temperature scaling the implicit reward difference.
        label_smoothing: Conservative smoothing probability.
        reference_free: If True, reference log ratios are treated as 0.

    Returns:
        losses: Per-pair SPIN loss tensor.
        chosen_rewards: Detached implicit rewards beta * (policy_chosen - ref_chosen).
        rejected_rewards: Detached implicit rewards beta * (policy_rejected - ref_rejected).
    """
    pi_logratios = policy_chosen_logps - policy_rejected_logps
    if reference_free:
        ref_logratios = torch.zeros_like(pi_logratios)
    else:
        ref_logratios = reference_chosen_logps - reference_rejected_logps

    logits = pi_logratios - ref_logratios
    losses = -F.logsigmoid(beta * logits) * (1.0 - label_smoothing) - F.logsigmoid(-beta * logits) * label_smoothing

    chosen_rewards = beta * (policy_chosen_logps - reference_chosen_logps).detach()
    rejected_rewards = beta * (policy_rejected_logps - reference_rejected_logps).detach()
    return losses, chosen_rewards, rejected_rewards


@CRITERIONS.register("spin", source="APSP/trainers.py:89")
class SPIN(Criterion):
    """Self-Play Fine-Tuning (SPIN) criterion.

    Optimizes policy to distinguish real human demonstrations (chosen) from
    synthetic self-play responses generated by the model's past checkpoint (rejected).
    """

    needs_teacher: ClassVar[bool] = False

    class Config(BaseConfig):
        beta: float = 0.1
        label_smoothing: float = 0.0
        reference_free: bool = False
        average_log_prob: bool = False
        reduction: str = "mean"
        chunk_size: int = 1024

    def features(self) -> FeatureRequest:
        spec = TeacherSignalSpec(kind="sampled_logp") if not self.cfg.reference_free else None
        return FeatureRequest(
            student=SideRequest(logits="view"),
            teacher_signal=spec,
        )

    def forward(self, ctx: LossContext) -> LossOutput:
        n = _check_pairwise(ctx.batch, "spin")

        seq, _, mask = sequence_logps(
            ctx.student_logits(),
            ctx.batch["student.labels"],
            average=self.cfg.average_log_prob,
            chunk_size=self.cfg.chunk_size,
        )
        pol_chosen, pol_rejected = pairwise(seq)

        if not self.cfg.reference_free:
            if ctx.teacher is None or ctx.teacher.token_logp is None:
                raise ValueError(
                    "SPIN requires a teacher/reference model providing sampled_logp when reference_free=False"
                )
            ref_seq = (ctx.teacher.token_logp * mask).sum(-1)
            if self.cfg.average_log_prob:
                ref_seq = ref_seq / mask.sum(-1).clamp_min(1.0)
            ref_chosen, ref_rejected = pairwise(ref_seq)
        else:
            ref_chosen = torch.zeros_like(pol_chosen)
            ref_rejected = torch.zeros_like(pol_rejected)

        losses, chosen_rewards, rejected_rewards = spin_loss(
            pol_chosen,
            pol_rejected,
            ref_chosen,
            ref_rejected,
            beta=self.cfg.beta,
            label_smoothing=self.cfg.label_smoothing,
            reference_free=self.cfg.reference_free,
        )

        term = _reduction_term(losses, self.cfg.reduction, n)
        acc = (chosen_rewards > rejected_rewards).float().mean()
        margin = (chosen_rewards - rejected_rewards).mean()
        metrics = {
            "loss": losses.mean().detach(),
            "reward_chosen": chosen_rewards.mean(),
            "reward_rejected": rejected_rewards.mean(),
            "accuracy": acc,
            "margin": margin,
        }
        return LossOutput({"spin": term}, metrics=metrics)
